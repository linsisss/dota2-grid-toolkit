// Valve's own cursor pictures for «Курсор» (src/customize/CursorCreator.jsx): the list's icons and the
// faded guide on the canvas. `node scripts/make-cursor-guides.mjs <pack.zip> [out dir]` takes a copy of
// Dota's resource/cursor folder as a ZIP (d2pfx's «Default Cursor» pack is exactly that) and writes
// assets/dota-cursors/<id>.png for every id of CURSOR_ROLES: the largest picture up to 96 px (Valve's
// _vsz3; cursor_default_team_vsz3 is 1280 px in Valve's own folder, so its 64 px one is taken), and
// scripts/dota-cursor-valve.mjs: the fingerprints of every Valve picture in it (frameHash), so packs that
// left Valve's files beside their own are read by their own (dota-cursor.mjs packCursors).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createCanvas } from '@napi-rs/canvas';
import { readZip } from './zip.mjs';
import { CURSOR_IDS, decodeCursorBMP, frameHash, packCursors } from './dota-cursor.mjs';

const [source, out = 'assets/dota-cursors'] = process.argv.slice(2);
if (!source) { console.error('usage: node scripts/make-cursor-guides.mjs <pack.zip> [out dir]'); process.exit(1); }
const entries = await readZip(new Uint8Array(readFileSync(source)), { want: (name) => /\.(bmp|res)$/i.test(name) });
const hashes = [...new Set(entries.filter((entry) => /\.bmp$/i.test(entry.name)).map((entry) => decodeCursorBMP(entry.data)).filter(Boolean).map(frameHash))].sort();
writeFileSync('scripts/dota-cursor-valve.mjs', `// Generated by scripts/make-cursor-guides.mjs from Dota's resource/cursor: fingerprints (frameHash) of Valve's own cursor pictures.\nexport const VALVE_FRAME_HASHES = Object.freeze(${JSON.stringify(hashes)});\n`);
console.log(`${hashes.length} Valve pictures`);
const pack = packCursors(entries);
mkdirSync(out, { recursive: true });
for (const id of CURSOR_IDS) {
  const frame = pack[id]?.frames.find((picture) => picture.width <= 96);
  if (!frame) { console.warn(`${id}: not in the pack`); continue; }
  const canvas = createCanvas(frame.width, frame.height), ctx = canvas.getContext('2d'), image = ctx.createImageData(frame.width, frame.height);
  image.data.set(frame.rgba); ctx.putImageData(image, 0, 0);
  writeFileSync(join(out, `${id}.png`), canvas.toBuffer('image/png'));
  console.log(`${id}: ${frame.width} px`);
}

// Writes scripts/hero-portraits-data.mjs: for every hero of the site, Valve's name and the variants
// of its pictures and movie that the game has (alt1…, persona1, carnival: arcana styles, personas,
// event looks), so a hero's own portrait replaces all of them (scripts/hero-portraits.mjs).
//   node scripts/make-hero-portraits.mjs <pak01_dir.vpk> <depot manifest .txt>
// The pak01 directory lists the pictures (panorama/images/heroes/{selection/,,icons/}); the movies are
// loose files of the game (game/dota/panorama/videos/heroes/*.webm), listed by the depot's manifest
// (DepotDownloader -manifest-only). Run again after a Dota patch that adds a hero.
import { readFileSync, writeFileSync } from 'node:fs';
import { readVPK } from './vpk.mjs';

const [vpkPath, manifestPath] = process.argv.slice(2);
if (!vpkPath || !manifestPath) { console.error('node scripts/make-hero-portraits.mjs <pak01_dir.vpk> <manifest.txt>'); process.exit(1); }
const source = JSON.parse(readFileSync(new URL('../data/heroes-source.json', import.meta.url), 'utf8'));
const { default: D } = await import('./data.mjs');
const paths = new Set(readVPK(new Uint8Array(readFileSync(vpkPath))).files.map((file) => file.path));
const movies = new Set(readFileSync(manifestPath, 'utf8').split('\n').map((line) => /game\/dota\/(panorama\/videos\/heroes\/\S+\.webm)\s*$/.exec(line)?.[1]).filter(Boolean));
const KINDS = { card: 'panorama/images/heroes/selection/', wide: 'panorama/images/heroes/', icon: 'panorama/images/heroes/icons/' };
const names = new Set(Object.values(source).map((hero) => hero.name));
// The variants a hero's file names have: npc_dota_hero_<name>_<variant>, not another hero's name.
const variantsOf = (full, list, tail) => [...list].map((path) => path.split('/').pop()).filter((file) => file.startsWith(`${full}_`) && file.endsWith(tail))
  .map((file) => file.slice(full.length + 1, -tail.length)).filter((variant) => /^[a-z0-9]+$/.test(variant) && !names.has(`${full}_${variant}`)).sort();
const heroes = {};
for (const hero of D.heroes) {
  const full = source[hero.id]?.name;
  if (!full) continue;   // the site's own «Мишень»
  const entry = { name: full.replace('npc_dota_hero_', '') }, variants = {};
  for (const [kind, dir] of Object.entries(KINDS)) {
    if (!paths.has(`${dir}${full}_png.vtex_c`)) throw new Error(`${full}: no ${kind} picture in pak01`);
    const list = variantsOf(full, [...paths].filter((path) => path.startsWith(dir) && path.slice(dir.length).indexOf('/') < 0), '_png.vtex_c');
    if (list.length) variants[kind] = list;
  }
  if (!movies.has(`panorama/videos/heroes/${full}.webm`)) throw new Error(`${full}: no movie`);
  const movieVariants = variantsOf(full, movies, '.webm');
  if (movieVariants.length) variants.movie = movieVariants;
  if (Object.keys(variants).length) entry.variants = variants;
  heroes[hero.id] = entry;
}
const body = `// Generated by scripts/make-hero-portraits.mjs from Dota's pak01 directory and depot manifest (${new Date().toISOString().slice(0, 10)}).
// The site's hero id → Valve's name (npc_dota_hero_<name>) and the variants of its pictures and movie.
export default ${JSON.stringify(heroes, null, 0).replace(/},"/g, '},\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, '\n}')};
`;
writeFileSync(new URL('./hero-portraits-data.mjs', import.meta.url), body);
console.log(`${Object.keys(heroes).length} heroes, ${Object.values(heroes).filter((hero) => hero.variants).length} with variants`);
